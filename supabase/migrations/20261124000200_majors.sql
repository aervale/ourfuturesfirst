-- Majors offered as suggestions. dom = '' is the national list; any other dom is that university's own list,
-- shown first for people with that university's email. Anything typed is still accepted.
create table public.majors (
  dom  text not null default '',
  name text not null,
  pos  int  not null default 0,
  primary key (dom, name)
);
alter table public.majors enable row level security;

create function public.majors_for(p_dom text) returns jsonb
language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(name order by pos, lower(name)), '[]'::jsonb) from majors where dom = coalesce(p_dom, '');
$$;
revoke execute on function public.majors_for(text) from public, anon, authenticated;
grant execute on function public.majors_for(text) to anon, authenticated;

